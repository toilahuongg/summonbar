import AppKit
import CryptoKit

struct ClipboardEntry: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, files, image }

    var id: UUID
    var kind: Kind
    /// The copied text, for `.text`.
    var text: String?
    /// Absolute paths, for `.files`.
    var paths: [String]?
    /// PNG file name under `ClipboardHistory.imagesDirectory`, for `.image`.
    var image: String?
    /// Identifies the content, so copying the same thing again moves it to the top.
    var digest: String
    var date: Date
    /// The app that was frontmost when it was copied.
    var sourceApp: String?
    var pinned: Bool?

    var isPinned: Bool { pinned == true }
    var imageURL: URL? { image.map { ClipboardHistory.imagesDirectory.appendingPathComponent($0) } }
    var fileURLs: [URL] { (paths ?? []).map { URL(fileURLWithPath: $0) } }

    /// One line for the list.
    var title: String {
        switch kind {
        case .text:
            let line = (text ?? "").split(whereSeparator: \.isNewline)
                .first { !$0.allSatisfy(\.isWhitespace) }.map(String.init) ?? ""
            let collapsed = line.split(whereSeparator: \.isWhitespace).joined(separator: " ")
            return collapsed.count > 200 ? String(collapsed.prefix(200)) + "…" : collapsed
        case .files:
            let names = fileURLs.map(\.lastPathComponent)
            return names.count == 1 ? names[0] : "\(names.count) files: " + names.joined(separator: ", ")
        case .image:
            return "Image"
        }
    }

    /// A web address on its own, so it can be opened.
    var link: URL? {
        guard kind == .text, let text = text?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.contains(where: \.isWhitespace), let url = URL(string: text),
              ["http", "https"].contains(url.scheme?.lowercased() ?? "") else { return nil }
        return url
    }

    func matches(_ query: String) -> Bool {
        let haystack: String
        switch kind {
        case .text: haystack = text ?? ""
        case .files: haystack = (paths ?? []).joined(separator: "\n")
        case .image: haystack = "image"
        }
        return query.split(separator: " ").allSatisfy { haystack.localizedCaseInsensitiveContains($0) }
            || sourceApp?.localizedCaseInsensitiveContains(query) == true
    }
}

/// Watches the general pasteboard and keeps what's copied. macOS has no change notification,
/// so it polls `changeCount`, which is cheap.
@MainActor
final class ClipboardHistory {
    nonisolated static let imagesDirectory: URL = {
        let dir = Store.directory.appendingPathComponent("clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }()

    /// Password managers mark what they copy with these (nspasteboard.org), so it's never saved.
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]
    private static let skippedApps: Set<String> = ["com.apple.keychainaccess", "com.apple.Passwords"]
    /// Bigger text or images aren't saved.
    private static let maxBytes = 10_000_000

    private(set) var entries: [ClipboardEntry]
    var onChange: (() -> Void)?

    private var limit = 200
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var saveWork: DispatchWorkItem?

    init() {
        entries = Store.loadClipboard()
    }

    var isMonitoring: Bool { timer != nil }

    func configure(_ config: ClipboardConfig) {
        limit = config.limit
        if config.isEnabled, timer == nil {
            lastChangeCount = NSPasteboard.general.changeCount
            let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.poll() }
            }
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
        } else if !config.isEnabled {
            timer?.invalidate()
            timer = nil
        }
        trim()
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication
        if let id = source?.bundleIdentifier, Self.skippedApps.contains(id) { return }
        guard var entry = Self.read(pasteboard) else { return }
        entry.sourceApp = source?.localizedName
        add(entry)
    }

    /// Files first (Finder also puts their names on the pasteboard as text), then images, then text.
    private static func read(_ pasteboard: NSPasteboard) -> ClipboardEntry? {
        let new = { (kind: ClipboardEntry.Kind, digest: String) in
            ClipboardEntry(id: UUID(), kind: kind, digest: digest, date: Date())
        }
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            var entry = new(.files, digest(urls.map(\.path).joined(separator: "\n")))
            entry.paths = urls.map(\.path)
            return entry
        }
        if pasteboard.string(forType: .string) == nil, let png = pngData(pasteboard), png.count <= maxBytes {
            let hash = digest(png)
            var entry = new(.image, hash)
            entry.image = hash + ".png"
            let url = imagesDirectory.appendingPathComponent(hash + ".png")
            if !FileManager.default.fileExists(atPath: url.path) {
                guard (try? png.write(to: url, options: .atomic)) != nil else { return nil }
            }
            return entry
        }
        if let text = pasteboard.string(forType: .string), !text.allSatisfy(\.isWhitespace), text.utf8.count <= maxBytes {
            var entry = new(.text, digest(text))
            entry.text = text
            return entry
        }
        return nil
    }

    private static func pngData(_ pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private static func digest(_ string: String) -> String { digest(Data(string.utf8)) }

    private static func digest(_ data: Data) -> String {
        SHA256.hash(data: data).prefix(16).map { String(format: "%02x", $0) }.joined()
    }

    private func add(_ entry: ClipboardEntry) {
        var entry = entry
        if let i = entries.firstIndex(where: { $0.digest == entry.digest }) {
            entry.pinned = entries[i].pinned
            entries.remove(at: i)
        }
        entries.insert(entry, at: 0)
        trim()
        changed()
    }

    /// Puts an entry back on the pasteboard and moves it to the top.
    func copy(_ entry: ClipboardEntry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch entry.kind {
        case .text:
            pasteboard.setString(entry.text ?? "", forType: .string)
        case .files:
            pasteboard.writeObjects(entry.fileURLs as [NSURL])
        case .image:
            if let url = entry.imageURL, let image = NSImage(contentsOf: url) { pasteboard.writeObjects([image]) }
        }
        // Our own write, so the poll doesn't take the frontmost app for its source.
        lastChangeCount = pasteboard.changeCount
        var moved = entry
        moved.date = Date()
        entries.removeAll { $0.id == entry.id }
        entries.insert(moved, at: 0)
        changed()
    }

    func togglePin(_ entry: ClipboardEntry) {
        guard let i = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[i].pinned = entries[i].isPinned ? nil : true
        changed()
    }

    func delete(_ entry: ClipboardEntry) {
        entries.removeAll { $0.id == entry.id }
        removeUnusedImages()
        changed()
    }

    /// Clears everything except pinned entries.
    func clear() {
        entries.removeAll { !$0.isPinned }
        removeUnusedImages()
        changed()
    }

    /// Keeps the newest `limit` entries; pinned ones don't count.
    private func trim() {
        var kept = 0
        let before = entries.count
        entries.removeAll { entry in
            guard !entry.isPinned else { return false }
            kept += 1
            return kept > limit
        }
        if entries.count != before { removeUnusedImages() }
    }

    private func removeUnusedImages() {
        let used = Set(entries.compactMap(\.image))
        let files = (try? FileManager.default.contentsOfDirectory(atPath: Self.imagesDirectory.path)) ?? []
        for name in files where !used.contains(name) {
            try? FileManager.default.removeItem(at: Self.imagesDirectory.appendingPathComponent(name))
        }
    }

    private func changed() {
        onChange?()
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self.map { Store.saveClipboard($0.entries) } }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5, execute: work)
    }

    func saveNow() {
        guard saveWork != nil else { return }
        saveWork?.cancel()
        saveWork = nil
        Store.saveClipboard(entries)
    }
}
